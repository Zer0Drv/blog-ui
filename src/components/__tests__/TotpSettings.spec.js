import { beforeEach, describe, expect, it, vi } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'
import ElementPlus, { ElMessageBox } from 'element-plus'
import TotpSettings from '../TotpSettings.vue'
import http from '../../api/http'
import { toDataURL } from 'qrcode'
const mocks = vi.hoisted(() => ({ replace: vi.fn(), expireSession: vi.fn(), leave: null }))
vi.mock('vue-router', () => ({ useRouter: () => ({ replace: mocks.replace }), onBeforeRouteLeave: fn => { mocks.leave = fn } }))
vi.mock('../../stores/auth', () => ({ useAuthStore: () => ({ expireSession: mocks.expireSession }) }))
vi.mock('../../api/http', () => ({ default: { get: vi.fn(), post: vi.fn() } }))
vi.mock('qrcode', () => ({ toDataURL: vi.fn() }))
const button = (w, text) => w.findAll('button').find(b => b.text() === text)
const mountCard = () => mount(TotpSettings, { global: { plugins: [ElementPlus] } })
describe('TOTP 设置', () => {
  beforeEach(() => {
    vi.resetAllMocks()
    http.get.mockResolvedValue({ enabled: false, available: true, recoveryRemaining: 0 })
    toDataURL.mockResolvedValue('data:image/png;base64,cXJjb2Rl')
    vi.spyOn(ElMessageBox, 'confirm').mockResolvedValue('confirm')
  })
  it('本地二维码绑定，确认后只展示一次恢复码并保护离开', async () => {
    http.post.mockResolvedValueOnce({ secret: 'SECRET', uri: 'otpauth://totp/Blog:test?secret=SECRET' }).mockResolvedValueOnce(['recovery-one', 'recovery-two'])
    const w = mountCard(); await flushPromises()
    await w.find('input[type="password"]').setValue('password')
    await button(w, '开始绑定').trigger('click'); await flushPromises()
    expect(toDataURL).toHaveBeenCalledWith('otpauth://totp/Blog:test?secret=SECRET', { width: 220, margin: 2 })
    expect(w.find('img').attributes('src')).toMatch(/^data:/)
    await w.find('input[autocomplete="one-time-code"]').setValue('123456')
    await button(w, '确认开启').trigger('click'); await flushPromises()
    expect(http.post).toHaveBeenLastCalledWith('/auth/totp/confirm', { password: 'password', code: '123456' })
    expect(mocks.expireSession).toHaveBeenCalledOnce()
    expect(w.text()).toContain('recovery-one')
    expect(w.text()).not.toContain('SECRET')
    expect(mocks.leave()).toBe(false)
    expect(button(w, '重新登录').attributes('disabled')).toBeDefined()
    await w.find('input[type="checkbox"]').setValue(true)
    expect(mocks.leave()).toBe(true)
    await button(w, '重新登录').trigger('click'); await flushPromises()
    expect(mocks.replace).toHaveBeenCalledWith('/login')
    expect(w.text()).not.toContain('recovery-one')
    w.unmount()
  })
  it('绑定请求失败不虚报开启，可重试', async () => {
    http.post.mockRejectedValue(new Error('wrong password'))
    const w = mountCard(); await flushPromises()
    await w.find('input[type="password"]').setValue('bad')
    await button(w, '开始绑定').trigger('click'); await flushPromises()
    expect(w.text()).toContain('尚未开启')
    expect(w.find('img').exists()).toBe(false)
    expect(mocks.expireSession).not.toHaveBeenCalled()
    w.unmount()
  })
  it('取消关闭不调用 API；确认需要密码与第二因子', async () => {
    http.get.mockResolvedValue({ enabled: true, available: true, recoveryRemaining: 5 })
    const w = mountCard(); await flushPromises()
    await w.find('input[type="password"]').setValue('password')
    await w.find('input[autocomplete="one-time-code"]').setValue('recovery')
    ElMessageBox.confirm.mockRejectedValueOnce('cancel')
    await button(w, '关闭两步验证').trigger('click'); await flushPromises()
    expect(http.post).not.toHaveBeenCalled()
    await button(w, '关闭两步验证').trigger('click'); await flushPromises()
    expect(http.post).toHaveBeenCalledWith('/auth/totp/disable', { password: 'password', code: 'recovery' })
    expect(mocks.expireSession).toHaveBeenCalledOnce()
    w.unmount()
  })
})
